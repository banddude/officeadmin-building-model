from dataclasses import asdict, replace
import hashlib
import json

from oabm.drawings import PlanSpec, generate_drawing_set
from oabm.electrical import (RacewayCatalogEntry, RacewayIntent, RacewayRule,
    select_raceways)
from oabm.electrical.catalog_manifest import CatalogManifest
from oabm.electrical.fittings import FittingIntent, FittingPortBinding, select_route_fittings
from oabm.exports.gltf import build_glb_bytes
from oabm.ifc.adapter import from_ifc, to_ifc
from oabm.model import (BuildingModel, CatalogProduct, Level, Point3, Port, Pose,
    Provenance, RouteFitting, RuleReference, Vector3,
    upgrade_to_v1_2, upgrade_to_v1_5)
from oabm.pipeline.saved_route_fitting_replay import VERSION, replay_saved_route_fitting
from oabm.quantities import extract_quantities
from oabm.routing import route_between_ports

from test_route_fittings import COUPLING_PRODUCT, catalog_manifest, rule_for
from test_routing import _base_model


def _dump(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()


def _sha(payload):
    return hashlib.sha256(payload).hexdigest()


def _save_reference(root, relative, payload):
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(payload)
    return {"path": relative, "bytes": len(payload), "sha256": _sha(payload)}


def _routed_caller_input():
    level = Level(id="level:routed-fitting", elevation_m=0.0, name="Synthetic route level")
    base = _base_model()
    base = replace(base, name="Synthetic routed fitting model")
    source = replace(base.electrical_equipment[0], level_id=level.id)
    load = replace(base.electrical_devices[0], level_id=level.id)
    base = replace(base, levels=(level,), electrical_equipment=(source,), electrical_devices=(load,))

    # The canonical route is the output of the production router, not a hand
    # assembled Route. It is intentionally straight and bend-free.
    routed_route, router_fittings = route_between_ports(
        base, "port:source", "port:load", "emt", nominal_diameter_m=0.0213,
    )
    assert router_fittings == ()
    base = replace(base, routes=(routed_route,), route_fittings=router_fittings)

    # A caller now supplies a physical fitting and four existing ports. No
    # router or fitting selector creates or moves any of these objects.
    tangent = Vector3(x=1.0, y=0.0, z=0.0)
    fitting = RouteFitting(id="fitting:caller-coupling", route_id=routed_route.id,
        fitting_type="coupling", pose=Pose(position=Point3(x=2.0, y=0.0, z=0.0)))
    route = replace(routed_route, fitting_ids=(fitting.id,))
    ports = (
        Port(id="port:caller-fit-a", owner_id=fitting.id, domain="power", role="fitting",
            pose=Pose(position=Point3(x=1.5, y=0.0, z=0.0)), direction=Vector3(x=-1.0, y=0.0, z=0.0),
            connected_port_ids=("port:caller-run-a",)),
        Port(id="port:caller-run-a", owner_id=route.id, domain="power", role="run_end",
            pose=Pose(position=Point3(x=1.5, y=0.0, z=0.0)), direction=tangent,
            connected_port_ids=("port:caller-fit-a",)),
        Port(id="port:caller-fit-b", owner_id=fitting.id, domain="power", role="fitting",
            pose=Pose(position=Point3(x=2.5, y=0.0, z=0.0)), direction=tangent,
            connected_port_ids=("port:caller-run-b",)),
        Port(id="port:caller-run-b", owner_id=route.id, domain="power", role="run_end",
            pose=Pose(position=Point3(x=2.5, y=0.0, z=0.0)), direction=Vector3(x=-1.0, y=0.0, z=0.0),
            connected_port_ids=("port:caller-fit-b",)),
    )
    base = replace(base, routes=(route,), route_fittings=(fitting,),
        ports=tuple(sorted((*base.ports, *ports), key=lambda row: row.id)))

    route_product = CatalogProduct(catalog_id="raceway-catalog", catalog_revision="r1",
                                   product_id="emt-1")
    route_basis = RuleReference(authority="synthetic-caller", revision="r1", rule_id="route-permission")
    catalog_provenance = (Provenance(source_kind="caller", source_id="synthetic-route-catalog",
        derivation="user", scope_paths=("product", "route_type", "wiring_method",
            "designation_kind", "designation", "nominal_diameter_m")),)
    route_entry = RacewayCatalogEntry(product=route_product, route_type="emt", wiring_method="raceway",
        designation_kind="trade_size", designation="synthetic EMT trade designation",
        nominal_diameter_m=0.0213, provenance=catalog_provenance)
    route_rule = RacewayRule(reference=route_basis, product=route_product, route_type="emt",
        provenance=(Provenance(source_kind="caller", source_id="synthetic-route-rule",
            derivation="user", scope_paths=("basis",)),))
    route_intent = RacewayIntent(intent_id="route-intent:routed-fitting", route_id=route.id,
        actor_id="synthetic-caller", product=route_product, basis=route_basis)
    base = select_raceways(upgrade_to_v1_2(base), intents=(route_intent,),
                           catalog=(route_entry,), rules=(route_rule,))

    fitting_input = FittingIntent(intent_id="fitting-intent:routed-coupling", fitting_id=fitting.id,
        actor_id="synthetic-caller", requested_product=COUPLING_PRODUCT,
        basis=rule_for(COUPLING_PRODUCT, "coupling").reference,
        bindings=(
            FittingPortBinding(interface_key="end_a", mating_interface_key="run_end",
                fitting_port_id="port:caller-fit-a", counterpart_port_id="port:caller-run-a"),
            FittingPortBinding(interface_key="end_b", mating_interface_key="run_end",
                fitting_port_id="port:caller-fit-b", counterpart_port_id="port:caller-run-b"),
        ))
    fitting_rule = rule_for(COUPLING_PRODUCT, "coupling")
    manifest = catalog_manifest()
    drawing_plans = (PlanSpec(id="plan:routed-fitting", level_id=level.id,
        cut_height_m=1.0, view_depth_below_m=0.2, view_depth_above_m=0.2, scale=40.0),)
    # Replay starts from this exact serialized canonical boundary; decoding it
    # also normalizes integral numeric tokens to the model's portable values.
    base = upgrade_to_v1_5(base)
    base = BuildingModel.from_json(base.to_json(indent=None))
    return base, fitting_input, fitting_rule, manifest, drawing_plans


def _outputs(base, intent, rule, manifest, plans):
    selected = select_route_fittings(base, intents=(intent,), catalog=manifest, rules=(rule,))
    return selected, {
        "canonical_model": selected.to_json(indent=None).encode(),
        "quantities": extract_quantities(selected).to_json(indent=None).encode(),
        "glb": build_glb_bytes(selected),
        "ifc": to_ifc(selected).to_string().encode(),
        "drawings": generate_drawing_set(selected, plans=plans).to_json(indent=None).encode(),
    }


def test_actual_router_route_selection_and_caller_fitting_replay_vertical_slice(tmp_path):
    base, intent, rule, manifest, plans = _routed_caller_input()
    route_before, fittings_before, ports_before = base.routes, base.route_fittings, base.ports
    selected, outputs = _outputs(base, intent, rule, manifest, plans)
    assert selected.routes == route_before
    assert selected.route_fittings == fittings_before
    assert selected.ports == ports_before
    assert selected.fitting_selection_outcomes[0].status == "selected"
    assert selected.fitting_interfaces[0].mating_product.product_id == "emt-1"
    quantities = extract_quantities(selected)
    fitting_lines = [row for row in quantities.items if row.category == "fitting"]
    assert len(fitting_lines) == 1 and fitting_lines[0].quantity == 1.0
    assert fitting_lines[0].source_entity_ids == ("fitting:caller-coupling",)
    restored = from_ifc(to_ifc(selected))
    assert restored.to_dict() == selected.to_dict()
    assert any(primitive.source_ids and "fitting:caller-coupling" in primitive.source_ids
               for view in generate_drawing_set(selected, plans=plans).views
               for primitive in view.primitives)

    # Saved replay starts from the actually routed/whole-route-selected
    # canonical input, with caller-authored fitting topology but no fitting
    # decision rows. It reruns fitting selection and all consumers from bytes.
    payloads = {
        "base_model": base.to_json(indent=None).encode(),
        "catalog_manifest": manifest.raw,
        "intents": _dump({"version": "saved-route-fitting-intents-v1", "items": [asdict(intent)]}),
        "rules": _dump({"version": "saved-route-fitting-rules-v1", "items": [asdict(rule)]}),
        "drawing_plans": _dump({"version": "saved-route-fitting-plans-v1", "items": [{
            "id": plan.id, "level_id": plan.level_id, "cut_height_m": plan.cut_height_m,
            "view_depth_below_m": plan.view_depth_below_m,
            "view_depth_above_m": plan.view_depth_above_m, "scale": plan.scale,
        } for plan in plans]}),
    }
    input_refs = {key: _save_reference(tmp_path, f"inputs/{key}.json", data)
                  for key, data in payloads.items()}
    expected_refs = {key: _save_reference(tmp_path, f"expected/{key}.bin", data)
                     for key, data in outputs.items()}
    replay_manifest = {"version": VERSION, "inputs": input_refs, "expected_outputs": expected_refs}
    path = tmp_path / "replay.json"
    path.write_bytes(_dump(replay_manifest))
    receipt = replay_saved_route_fitting(path)
    assert receipt["application_mode"] == "first_application"
    assert receipt["freshly_regenerated_outputs"] == [
        "canonical_model", "drawings", "glb", "ifc", "quantities",
    ]
    assert receipt["output_receipts"]["canonical_model"]["actual"]["sha256"] == _sha(outputs["canonical_model"])
